package curate

import (
	"reflect"
	"testing"

	"github.com/agent-sh/tacit/client/internal/fact"
)

func rf(path, name, scope, kind, desc string) *fact.Fact {
	return &fact.Fact{Path: path, Meta: fact.Meta{Name: name, Scope: scope, Description: desc, Source: fact.Source{Kind: kind}}, Body: desc + "\n"}
}

func TestRestated(t *testing.T) {
	curated := []*fact.Fact{
		rf("machines/ws/app-config.md", "app-config", "machines/ws", "observed", "/home/u/app/config.yaml is generated by confgen from ~/app/config.src.yaml; edit config.src.yaml, not config.yaml"),
		rf("projects/memra/lantern-port.md", "lantern-port", "projects/memra", "observed", "The lantern proxy for the quokka scheduler listens on port 7781 on the host-a"),
		rf("projects/other/zebra.md", "zebra", "projects/other", "observed", "zebra crossing tool writes its receipts under receipts/zebra in the repo root"),
		rf("user/deploy-retry.md", "deploy-retry", "user", "observed", "Never retry a failed deploy by hand in a loop; rerun it with the deploy tool and a timeout"),
	}
	pending := []*fact.Fact{
		// The same fact, other words: dropped.
		rf("inbox/d/a.md", "a", "machines/ws", "observed", "The /home/u/app/config.yaml file is generated by confgen from ~/app/config.src.yaml, so edit config.src.yaml and not config.yaml"),
		// Same words, a new port: an update the conflict check must see.
		rf("inbox/d/b.md", "b", "projects/memra", "observed", "The lantern proxy for the quokka scheduler listens on port 7790 on the host-a"),
		// Another repo's fact restated in this repo: not visible, stays.
		rf("inbox/d/c.md", "c", "projects/memra", "observed", "zebra crossing tool writes its receipts under receipts/zebra in the repo root"),
		// Their words against an agent's paraphrase: stays.
		rf("inbox/d/d.md", "d", "user", "user", "Never retry a failed deploy by hand in a loop; rerun it with the deploy tool and a timeout"),
		// Two pending notes on one fact: the second goes.
		rf("inbox/d/e.md", "e", "projects/memra", "observed", "api pre-push hook needs PATH=$HOME/.local/node/bin because eslint is not on the hook's PATH"),
		rf("inbox/d/f.md", "f", "projects/memra", "observed", "The api pre-push hook needs PATH=$HOME/.local/node/bin since eslint is not on the hook's PATH"),
	}
	// Found in review: each of these restated the wording and changed the fact.
	curated = append(curated,
		rf("projects/memra/hook-path.md", "hook-path", "projects/memra", "observed", "api pre-push hook needs PATH=$HOME/.local/node/bin because eslint is missing from the hook PATH"),
		rf("projects/memra/resident.md", "resident", "projects/memra", "observed", "the api server needs the warm cache flag on the host-a for the large index"),
		rf("projects/memra/proxy-port.md", "proxy-port", "projects/memra", "observed", "The quokka lantern proxy answers on port 7781 for the host-a scheduler"))
	reason := rf("inbox/d/k.md", "k", "projects/memra", "observed", "the api server needs the warm cache flag on the host-a for the large index")
	reason.Body = "the api server needs the warm cache flag on the host-a for the large index. Without it the index pages from disk and queries slow down by half.\n"
	pending = append(pending,
		// A negation search.Terms drops: stays.
		rf("inbox/d/g.md", "g", "projects/memra", "observed", "the api server does not need the warm cache flag on the host-a for the large index"),
		// A change word: stays.
		rf("inbox/d/h.md", "h", "projects/memra", "observed", "api pre-push hook no longer needs PATH=$HOME/.local/node/bin because eslint is missing from the hook PATH"),
		// A user note against a repo fact widens it: stays.
		rf("inbox/d/i.md", "i", "user", "observed", "the api server needs the warm cache flag on the host-a for the large index"),
		// A number that is a prefix of the fact's: stays.
		rf("inbox/d/j.md", "j", "projects/memra", "observed", "The quokka lantern proxy answers on port 778 for the host-a scheduler"),
		// A body that adds a reason: stays.
		reason)
	got := Restated(pending, curated)
	want := map[string]string{"a": "app-config", "f": "e"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Restated = %v, want %v", got, want)
	}
}

func TestRestatedKeepsFactWhenNegationWasRemoved(t *testing.T) {
	old := rf("machines/fixture/old.md", "old", "machines/fixture", "observed", "Fixture controller revision 7 requires synchronous reads; asynchronous reads are not supported on that revision.")
	note := rf("inbox/muse/new.md", "new", "machines/fixture", "observed", "Fixture controller revision 7 requires asynchronous reads")
	if got := Restated([]*fact.Fact{note}, []*fact.Fact{old}); len(got) != 0 {
		t.Fatalf("a changed fact was suppressed: %v", got)
	}
}
