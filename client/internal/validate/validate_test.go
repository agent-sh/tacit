func write(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// env is a machine with checkouts widget (origin widget-svc) and, under a
// symlink, atlas (lexically "orbit"), and a store with project folders
// widget and legacy (no checkout here), a derived folder, two machines.
func env(t *testing.T) Env {
	t.Helper()
	home, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(home, "projects")
	write(t, filepath.Join(p, "widget", ".git", "HEAD"), "ref: refs/heads/main\n")
	write(t, filepath.Join(p, "widget", ".git", "config"), "[remote \"origin\"]\n\turl = git@example.com:acme/widget-svc.git\n")
	write(t, filepath.Join(p, "atlas", ".git", "HEAD"), "ref: refs/heads/main\n")
	if err := os.MkdirAll(filepath.Join(p, "scratch-folder"), 0o755); err != nil {
		t.Fatal(err)
	}
	store := filepath.Join(home, "store")
	write(t, filepath.Join(store, "projects", "widget", "a.md"), "x")
	write(t, filepath.Join(store, "projects", "legacy", "b.md"), "x")
	write(t, filepath.Join(store, "projects", "empty", fact.IndexFile), "x") // an index alone is no fact
	write(t, filepath.Join(store, "derived", "tool", "tool-hot-spots.md"), "x")
	write(t, filepath.Join(store, "machines", "host-b", "c.md"), "x")
	write(t, filepath.Join(store, "keys", "codex@laptop.pub"), "k")
	cat := repoid.LoadCatalog(home, "", p)
	if runtime.GOOS != "windows" {
		if err := os.Symlink("atlas", filepath.Join(p, "orbit")); err == nil {
			if r, ok := repoid.Of(filepath.Join(p, "orbit"), home); ok {
				cat.Add(r)
			}
		}
	}
	return NewEnv(store, "", cat, "box")
}

func TestScopeNamesOnlyWhatExists(t *testing.T) {
	e := env(t)
	ok := []string{"user", "system", "projects/widget", "projects/atlas", "projects/legacy", "projects/tool", "machines/box", "machines/host-b", "machines/laptop"}
	for _, s := range ok {
		if p := e.Scope(s); p != nil {
			t.Errorf("Scope(%s) refused: %s", s, p.Message())
		}
	}
	for s, rule := range map[string]string{
		"":                        "empty",
		"projects/scratch-folder": "names no known repository", // a folder under ~/projects with no git root
		"projects/exp-013-g1":     "names no known repository", // a task worktree's folder name
		"projects/tune":           "names no known repository", // a scratch dir outside home
		"projects/empty":          "names no known repository",
		"projects/widget-svc":     "another name of a repository",
		"machines/nowhere":        "names no known machine",
		"derived/widget":          "derived/ is for facts code generates",
		"projects/Widget":         "not user, system",
		"projects/a/b":            "not user, system",
		"inbox/claude@box":        "not user, system",
	} {
		p := e.Scope(s)
		if p == nil || !strings.Contains(p.Rule, rule) {
			t.Errorf("Scope(%q) = %v, want a refusal %q", s, p, rule)
		}
	}
	if p := e.Scope("projects/widget-svc"); p == nil || !strings.Contains(p.Hint, "use projects/widget") {
		t.Errorf("an alias scope's hint does not name the repository: %v", p)
	}
	if runtime.GOOS != "windows" {
		if p := e.Scope("projects/orbit"); p == nil || !strings.Contains(p.Hint, "projects/atlas") {
			t.Errorf("a symlink's name as a scope: %v", p)
		}
	}
}

func TestTypes(t *testing.T) {
	for _, c := range []struct {
		typ, scope string
		inbox      bool
		rule       string
	}{
		{"past_mistake", "projects/widget", false, ""},
		{"user", "user", false, ""},
		{"unclassified", "user", true, ""},
		{"hot_spot", "projects/widget", false, "generated by code"}, // the audit's model-written hot_spot facts
		{"result", "projects/widget", false, "generated by code"},
		{"result_ref", "user", true, "generated by code"},
		{"user", "projects/widget", false, "belongs in the user scope"},
		{"unclassified", "user", false, "inbox notes only"},
		{"feedback", "user", false, "not a known type"},
		{"", "user", false, "empty"},
	} {
		p := Type(c.typ, c.scope, c.inbox)
		switch {
		case c.rule == "" && p != nil:
			t.Errorf("Type(%s, %s) refused: %s", c.typ, c.scope, p.Message())
		case c.rule != "" && (p == nil || !strings.Contains(p.Rule, c.rule)):
			t.Errorf("Type(%s, %s) = %v, want %q", c.typ, c.scope, p, c.rule)
		}
	}
}

// Every type has its documentation, and lint's set and the documented list
// are one list.
func TestEveryTypeIsDocumented(t *testing.T) {
	if len(fact.TypeDocs) != len(fact.Types) {
		t.Fatalf("%d documented types, %d known", len(fact.TypeDocs), len(fact.Types))
	}
	for _, d := range fact.TypeDocs {
		if !fact.Types[d.Name] || strings.TrimSpace(d.Doc) == "" {
			t.Errorf("type %s: known %v, doc %q", d.Name, fact.Types[d.Name], d.Doc)
		}
	}
	for _, m := range fact.ModelTypes() {
		if d, _ := fact.TypeDocOf(m); d.Generated || d.InboxOnly {
			t.Errorf("%s is offered to models", m)
		}
	}
}

