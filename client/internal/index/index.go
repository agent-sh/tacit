// Package index generates MEMORY.md from fact frontmatter.
package index

import (
	"sort"
	"strings"

	"github.com/agent-sh/tacit/client/internal/fact"
)

// Generate renders the index: one line per non-superseded curated fact,
// grouped by scope, sorted by scope then name. Inbox facts are not indexed.
func Generate(facts []*fact.Fact) string {
	byScope := map[string][]*fact.Fact{}
	for _, f := range facts {
		if f.InInbox() || f.Meta.SupersededBy != "" || f.Meta.Retired != "" {
			continue
		}
		byScope[f.Meta.Scope] = append(byScope[f.Meta.Scope], f)
	}
	scopes := make([]string, 0, len(byScope))
	for s := range byScope {
		scopes = append(scopes, s)
	}
	sort.Strings(scopes)

	var b strings.Builder
	b.WriteString("# Memory index\n\nGenerated by `tacit index`. Do not edit.\n")
	for _, s := range scopes {
		fs := byScope[s]
		sort.Slice(fs, func(i, j int) bool { return fs[i].Meta.Name < fs[j].Meta.Name })
		b.WriteString("\n## " + s + "\n\n")
		for _, f := range fs {
			b.WriteString("- [" + f.Meta.Name + "](" + f.Path + ") - " + oneLine(f.Meta.Description) + "\n")
		}
	}
	return b.String()
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
