// resumeFixture is a transcript written for the resume tests.
type resumeFixture struct {
	name  string
	path  string
	f     digest.Format
	lines []string
}

// resumeFixtures are transcripts that hold what a line depends on in the
// lines before it: a Codex question before its answer (asked by a plain and
// by a namespaced call), a patch's end event before its output, a local
// command's caveat before its echo, a steer inside a running turn, a system
// line before a turn, a second turn's model and cwd, a call before its
// result; one Codex rollout is a compressed copy.
func resumeFixtures(t *testing.T, home string) []resumeFixture {
	t.Helper()
	caveat := []string{
		cl(0, `"type":"user","uuid":"u0","promptId":"p0",`+typedMarks+`,"message":{"role":"user","content":"keep the cache warm"}`),
		cl(1, `"type":"user","uuid":"c1","promptId":"p1","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}`),
		cl(1, `"type":"user","uuid":"c2","parentUuid":"c1","promptId":"p1",`+typedMarks+`,"message":{"role":"user","content":"<command-name>/auto-mode-setup</command-name>\n<command-message>auto-mode-setup</command-message>\n<command-args>--expect-sha256 abc --apply-file /home/u/x</command-args>"}`),
		cl(2, `"type":"assistant","uuid":"a3","message":{"model":"claude-sonnet-5-5","role":"assistant","content":[{"type":"text","text":"Set up."}]}`),
	}
	out := []resumeFixture{
		{"claude", filepath.Join(home, ".claude", "projects", "-home-u-projects-shop", claudeSession+".jsonl"), digest.Claude, claudeOwnerSession()},
		{"claude local command", filepath.Join(home, ".claude", "projects", "-home-u", "lc.jsonl"), digest.Claude, caveat},
		{"codex", filepath.Join(home, ".codex", "sessions", "2026", "10", "21", "rollout-2026-10-21T09-00-00-019a-own.jsonl"), digest.Codex, codexOwnerSession()},
		{"codex now", filepath.Join(home, ".codex", "sessions", "2026", "10", "29", "rollout-2026-10-29T09-00-00-019b-now.jsonl"), digest.Codex, codexNowSession()},
		{"codex namespaced question", filepath.Join(home, ".codex", "sessions", "2026", "10", "29", "rollout-2026-10-29T10-00-00-019c-ask.jsonl"), digest.Codex, codexAskSession()},
		{"codex compressed", filepath.Join(home, ".codex", "archived_sessions", "rollout-2026-10-21T09-00-00-019a-old.jsonl"), digest.Codex, codexOwnerSession()},
		{"pi", filepath.Join(home, ".pi", "agent", "sessions", "--home-u-projects-shop--", "2026-10-22T08-00-00-000Z_01pi.jsonl"), digest.Pi, piOwnerSession()},
	}
	for _, c := range out {
		write(t, c.path, c.lines...)
		if c.name == "codex compressed" {
			compress(t, c.path) // read by its plain path, from the copy
		}
	}
	return out
}

// A read from any line's offset gives exactly the events a read from the
// start gives from there: the same who, text, input kind, prior, tool names,
// error flags, model and cwd, so (Path, Offset, Index) names one event
// however the transcript is read.
func TestReadFromAnyLineIsTheFullRead(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("PI_CODING_AGENT_DIR", "")
	t.Setenv("PI_CODING_AGENT_SESSION_DIR", "")
	for _, c := range resumeFixtures(t, home) {
		path := c.path
		whole, end := readAll(t, path, c.f, 0)
		var off int64
		for i, l := range c.lines {
			rest, next := readAll(t, path, c.f, off)
			var want []Event
			for _, e := range whole {
				if e.Offset >= off {
					want = append(want, e)
				}
			}
			if next != end || !reflect.DeepEqual(rest, want) {
				t.Fatalf("%s: from line %d (offset %d):\n%s\nwant\n%s", c.name, i, off, dump(rest), dump(want))
			}
			off += int64(len(l)) + 1
		}
		// Stopped at every event in turn, a read from the cursor returned
		// gives the rest: nothing lost, nothing changed.
		stop := errors.New("stop")
		for n := range whole {
			k := 0
			var got []Event
			cursor, err := ReadFile(path, c.f, 0, func(e Event) error {
				if k == n {
					return stop
				}
				k++
				got = append(got, e)
				return nil
			})
			if !errors.Is(err, stop) || cursor != whole[n].Offset {
				t.Fatalf("%s: stopped at event %d: cursor %d (its line %d), %v", c.name, n, cursor, whole[n].Offset, err)
			}
			rest, _ := readAll(t, path, c.f, cursor)
			var before []Event
			for _, e := range got {
				if e.Offset < cursor {
					before = append(before, e)
				}
			}
			if all := append(before, rest...); !reflect.DeepEqual(all, whole) {
				t.Fatalf("%s: stopped at event %d and read again from %d:\n%s\nwant\n%s", c.name, n, cursor, dump(all), dump(whole))
			}
		}
	}
}

// A cursor holds while the transcript grows: a line still being written is
// left for the next read, then read whole; a cursor past the end is an
// error, and so is a store read as a transcript.
func TestReadFileCursorEdges(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	lines := []string{
		cl(0, `"type":"user","uuid":"u0",`+typedMarks+`,"message":{"role":"user","content":"keep the cache warm before a release"}`),
		cl(1, `"type":"assistant","uuid":"a1","message":{"model":"claude-opus-5-5","role":"assistant","content":[{"type":"text","text":"On it."}]}`),
	}
	path := write(t, filepath.Join(home, ".claude", "projects", "-home-u", "s.jsonl"), lines...)
	_, end := readAll(t, path, digest.Claude, 0)
	part := cl(4, `"type":"user","uuid":"u4",`+typedMarks+`,"message":{"role":"user","content":"and the docs"}`)
	f, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		t.Fatal(err)
	}
	f.WriteString(part[:len(part)/2])
	evs, next := readAll(t, path, digest.Claude, end)
	if len(evs) != 0 || next != end {
		t.Fatalf("half a line: %d events, cursor %d (want %d)", len(evs), next, end)
	}
	f.WriteString(part[len(part)/2:]) // whole, its newline not written yet
	f.Close()
	evs, next = readAll(t, path, digest.Claude, end)
	if len(evs) != 1 || evs[0].Text != "and the docs" || evs[0].Model != "claude-opus-5-5" || next != end+int64(len(part)) {
		t.Fatalf("whole line without its newline: %s cursor %d", dump(evs), next)
	}
	if evs, again := readAll(t, path, digest.Claude, next); len(evs) != 0 || again != next {
		t.Fatalf("at the end: %d events, cursor %d", len(evs), again)
	}
	if _, err := ReadFile(path, digest.Claude, next+1, func(Event) error { return nil }); !errors.Is(err, ErrPastEnd) {
		t.Fatalf("past the end: %v", err)
	}
	if _, err := ReadFile(path, digest.Hermes, 0, func(Event) error { return nil }); err == nil {
		t.Fatal("a Hermes store read as a transcript")
	}
}

// A Hermes read after any message id is the full read after it.
func TestReadHermesAfterAnyRowIsTheFullRead(t *testing.T) {
	t.Setenv("HOME", t.TempDir())
	path := filepath.Join(t.TempDir(), "state.db")
	st := hermestest.Create(t, path, hermestest.Session{ID: "phone", Source: "mobile", CreatedSource: "mobile", StartedAt: 100})
	st.Add(
		hermestest.Message{Session: "phone", Role: "user", Content: "prune the docker images", Timestamp: 101},
		hermestest.Message{Session: "phone", Role: "assistant", Content: "Pruning.", Finish: "tool_calls", Timestamp: 102,
			ToolCalls: `[{"id":"call_h1","call_id":"call_h1","type":"function","function":{"name":"terminal","arguments":"{}"}}]`},
		hermestest.Message{Session: "phone", Role: "tool", ToolCallID: "call_h1", Content: `{"output": "permission denied", "exit_code": 1}`, Timestamp: 103},
		hermestest.Message{Session: "phone", Role: "assistant", Content: "It failed.", Finish: "stop", Timestamp: 104},
		hermestest.Message{Session: "phone", Role: "user", Content: "use sudo then", Timestamp: 110},
	)
	db, err := hermes.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ss, err := db.Sessions(context.Background())
	if err != nil || len(ss) != 1 {
		t.Fatalf("sessions %v %v", ss, err)
	}
	read := func(after int64) []Event {
		var evs []Event
		if _, err := ReadHermes(context.Background(), db, ss[0], after, func(e Event) error {
			evs = append(evs, e)
			return nil
		}); err != nil {
			t.Fatal(err)
		}
		return evs
	}
	whole := read(0)
	for after := int64(0); after <= 5; after++ {
		var want []Event
		for _, e := range whole {
			if e.Offset > after {
				want = append(want, e)
			}
		}
		if got := read(after); !reflect.DeepEqual(got, want) {
			t.Fatalf("after %d:\n%s\nwant\n%s", after, dump(got), dump(want))
		}
	}
	// The tool row's name comes from its call, and the last turn's prior from
	// the reply before it, read after either.
	if r := read(2)[0]; r.ToolName != "terminal" || !r.IsError {
		t.Errorf("result after its call's row: %+v", r)
	}
	if u := read(4)[0]; u.Prior != "stop" {
		t.Errorf("turn after its reply's row: %+v", u)
	}
}
