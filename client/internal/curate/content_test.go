func curatedAt(scope, name, desc, body string) *fact.Fact {
	return &fact.Fact{Path: scope + "/" + name + ".md", Meta: fact.Meta{Name: name, Description: desc, Type: "machine_fact", Scope: scope, Source: fact.Source{Kind: "observed", Harness: "curator"}}, Body: body}
}

func dreamNote(scope, name, body string) *fact.Fact {
	return &fact.Fact{Path: "inbox/dreamer@h/" + name + ".md", Meta: fact.Meta{Name: name, Description: body, Type: "machine_fact", Scope: scope, Source: fact.Source{Kind: "observed", Harness: "dreamer"}}, Body: body}
}

// The measurement's case: a paraphrase of a curated fact whose description
// shares too few terms for the description rule, every claim in the cover.
func TestContentRuleAbsorbsAParaphrase(t *testing.T) {
	kept := curatedAt("machines/box", "agents-md-generated-by-agents-sync-1f708f",
		"AGENTS.md files are generated by agents-sync from ~/.config/agents/SHARED.md and codex-extra.md; edit those sources, never the generated AGENTS.md.",
		"Edits made directly to a generated AGENTS.md are overwritten on the next agents-sync.\n")
	a := NewAbsorber([]*fact.Fact{kept})
	f := curatedAt("machines/box", "agents-md-generated-by-agents-sync-cb6443",
		"AGENTS.md is generated by agents-sync from /home/u/.config/agents/SHARED.md and codex-extra.md; edit those sources, not the generated AGENTS.md.",
		"Edits made to a generated AGENTS.md are overwritten on the next agents-sync.\n")
	note := dreamNote("machines/box", "n1", f.Meta.Description)
	if by := a.Restates(f, false); by != "" {
		t.Fatalf("the description rule took it (%s): the fixture tests nothing", by)
	}
	ab, ok := a.Absorbs(f, false, note)
	if !ok || ab.Rule != "content" || ab.By != kept.Meta.Name || ab.ByPath != kept.Path || ab.Coverage < ContentCover || ab.Note != "n1" {
		t.Fatalf("not absorbed by content: %+v %v", ab, ok)
	}
}

func TestContentRuleGuards(t *testing.T) {
	base := curatedAt("machines/box", "quokka-port", "The quokka scheduler on the build host listens on port 7781 behind the proxy.", "Its health check is `curl -s localhost:7781/health`.\n")
	paths := curatedAt("machines/box", "workspace-logs", "Chromium apps in a workspace write stderr to /run/user/1000/ws/<workspace-id>/apps/<app-id>.stderr.log.", "Startup dbus errors there are not failures.\n")
	registered := curatedAt("machines/box", "fork-registered", "The fork avifenesh/codex-desktop-linux is registered with revuto for reviews.", "Reviews of its PRs run through revuto.\n")
	overview := curatedAt("projects/foreman", "_overview", "Foreman: the agent dispatcher of agent-sh, its runners, its config files, the decisions that shaped it and its open questions.", "A relayed decision is not owner approval for foreman agents; agents follow the PR procedure.\n")
	long := curatedAt("machines/box", "memory-import", "Imported memory of the box covering many tools.", strings.Repeat("The atrium daemon restarts nightly and the quokka scheduler on the build host listens behind the proxy. ", 14))
	other := curatedAt("projects/elsewhere", "elsewhere-fact", "The walrus cache lives in /srv/walrus/cache and is pruned weekly by walrus-prune.", "Pruning runs at 03:00.\n")
	sessionRepo := curatedAt("projects/tower-crane", "tc-agent-env", "Run tower-crane CLI as orchestrator with `export TOWER_CRANE_AGENT=orchestrator`, from ~/projects/agent-sh/tower-crane.", "Orchestrator commands need TOWER_CRANE_AGENT=orchestrator.\n")
	a := NewAbsorber([]*fact.Fact{base, paths, registered, overview, long, other, sessionRepo})
	cases := []struct {
		name  string
		f     *fact.Fact
		note  *fact.Fact
		wants bool
	}{
		{"same claim again", curatedAt("machines/box", "quokka-port-2", "The quokka scheduler on the build host listens on port 7781, behind the proxy.", "Health check: `curl -s localhost:7781/health`.\n"), nil, true},
		{"another port", curatedAt("machines/box", "quokka-port-3", "The quokka scheduler on the build host listens on port 7790 behind the proxy.", "\n"), nil, false},
		{"a new path past a placeholder", curatedAt("machines/box", "ws-logs-2", "Apps in a workspace write stderr to /run/user/1000/ws/<workspace-id>/apps/*.stderr.log.", "\n"), nil, false},
		{"a negation the cover lacks", curatedAt("machines/box", "fork-not-registered", "The fork avifenesh/codex-desktop-linux is not registered with revuto for reviews.", "\n"), nil, false},
		{"a folder overview is no cover", curatedAt("projects/foreman", "relayed", "A relayed decision is not owner approval for foreman agents.", "\n"), nil, false},
		{"a long import is no cover", curatedAt("machines/box", "atrium", "The atrium daemon restarts nightly.", "\n"), nil, false},
		{"another project's fact is not visible", curatedAt("projects/mine", "walrus", "The walrus cache lives in /srv/walrus/cache and is pruned weekly by walrus-prune.", "\n"), nil, false},
		{"the session's repository is visible", curatedAt("machines/box", "tc-env-2", "Run tower-crane orchestrator commands with `export TOWER_CRANE_AGENT=orchestrator` from ~/projects/agent-sh/tower-crane.", "\n"), dreamNote("projects/tower-crane", "tc-note", "x"), true},
		{"the session's repository from another note", curatedAt("machines/box", "tc-env-3", "Run tower-crane orchestrator commands with `export TOWER_CRANE_AGENT=orchestrator` from ~/projects/agent-sh/tower-crane.", "\n"), dreamNote("machines/box", "tc-note-2", "x"), false},
	}
	for _, c := range cases {
		if _, ok := a.Absorbs(c.f, false, c.note); ok != c.wants {
			t.Errorf("%s: absorbed %v, want %v", c.name, ok, c.wants)
		}
	}
}

// The owner's words are never absorbed by content: a note in their words, a
// statement, a quoted span of six words, a reviewer's trim.
func TestContentRuleKeepsTheOwnersWords(t *testing.T) {
	kept := curatedAt("user", "pr-procedure", "The PR procedure for agents is in ~/.config/agents/procedures/prs.md.", "Read ~/.config/agents/procedures/prs.md before opening or updating a PR.\n")
	a := NewAbsorber([]*fact.Fact{kept})
	f := func() *fact.Fact {
		return curatedAt("user", "pr-procedure-2", "Agents read ~/.config/agents/procedures/prs.md before opening or updating a PR.", "\n")
	}
	if by := a.Restates(f(), false); by != "" {
		t.Fatal("the description rule took it: the fixture tests nothing")
	}
	if ab, ok := a.Absorbs(f(), false, dreamNote("user", "plain", "x")); !ok || ab.Rule != "content" {
		t.Fatal("the plain copy was not absorbed: the fixture tests nothing")
	}
	user := dreamNote("user", "said", "x")
	user.Meta.Source.Kind = "user"
	quoted := dreamNote("user", "quoted", `The owner said "always read the PR procedure before any PR" today.`)
	trimmed := dreamNote("user", "agent-note-trimmed", "x")
	words := f()
	words.Meta.Source.OwnerWords = "read the procedure"
	for name, c := range map[string]struct{ f, note *fact.Fact }{
		"note in their words": {f(), user},
		"quoted span":         {f(), quoted},
		"reviewer trim":       {f(), trimmed},
		"fact with words":     {words, nil},
	} {
		if _, ok := a.Absorbs(c.f, false, c.note); ok {
			t.Errorf("%s: absorbed", name)
		}
	}
	if _, ok := a.Absorbs(f(), true, nil); ok {
		t.Error("a ruling was absorbed by content")
	}
}

// Claims may be covered by different facts; a retired fact covers nothing.
func TestContentRuleClaimsAcrossFactsAndDrop(t *testing.T) {
	one := curatedAt("machines/box", "restic-repo", "Local restic repo is /home/u/backups/restic for payload backups.", "\n")
	two := curatedAt("machines/box", "restic-password", "The restic password file lives under ~/.config/restic-pass for the local repo.", "\n")
	a := NewAbsorber([]*fact.Fact{one, two})
	f := curatedAt("machines/box", "restic-both", "Local restic repo is ~/backups/restic for payload backups.", "The restic password file lives under ~/.config/restic-pass for the local repo.\n")
	if _, ok := a.Absorbs(f, false, nil); !ok {
		t.Fatal("two claims covered by two facts were not absorbed")
	}
	a.Drop(two.Path)
	if _, ok := a.Absorbs(f, false, nil); ok {
		t.Fatal("a retired fact still covered a claim")
	}
}

func TestSentencesKeepCodeSpansWhole(t *testing.T) {
	got := sentences("Heartbeat: `timeout 40 ssh wrx 'cd ~/x; ls jobs'`. Then e.g. read it; done.\nNext")
	want := []string{"Heartbeat: `timeout 40 ssh wrx 'cd ~/x; ls jobs'`", "Then e.g. read it", "done", "Next"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("%q", got)
	}
}
