func TestClaudeSessionEvents(t *testing.T) {
	home := t.TempDir()
	lines := claudeOwnerSession()
	path := write(t, filepath.Join(home, ".claude", "projects", "-home-u-projects-shop", claudeSession+".jsonl"), lines...)
	evs, next := readAll(t, path, digest.Claude, 0)
	var size int64
	for _, l := range lines {
		size += int64(len(l)) + 1
	}
	if next != size {
		t.Fatalf("cursor %d, want the end %d", next, size)
	}
	got := byLine(t, lines, evs)

	const owner = "entrypoint cli"
	check(t, 0, got[0],
		want{Kind: KindHarnessText, Who: digest.Harness, Why: whyHarnessText, Text: "<system-reminder>\nthe background build finished\n</system-reminder>", InputKind: InputTyped},
		want{Kind: KindOwnerText, Who: digest.Owner, Why: owner, Text: "keep the cache warm before a release", InputKind: InputTyped})
	check(t, 1, got[1],
		want{Kind: KindAgentText, Who: digest.Agent, Why: whyAssistant, Text: "Checking the cache settings."},
		want{Kind: KindToolCall, Who: digest.Agent, ToolID: "toolu_01", ToolName: "Bash"})
	check(t, 2, got[2], want{Kind: KindToolResult, Who: digest.Harness, ToolID: "toolu_01", ToolName: "Bash", IsError: true})
	check(t, 3, got[3], want{Kind: KindToolCall, Who: digest.Agent, ToolID: "toolu_02", ToolName: "Read"})
	check(t, 4, got[4], want{Kind: KindHarnessText, Who: digest.Harness, Why: "hook PreToolUse", Text: "- shop-cache: agent note (2026-10-01): the cache key holds the lockfile hash", ToolID: "toolu_02"})
	check(t, 5, got[5], want{Kind: KindToolResult, Who: digest.Harness, ToolID: "toolu_02", ToolName: "Read"})
	check(t, 6, got[6], want{Kind: KindOwnerText, Who: digest.Owner, Text: "and never purge the cache on main", InputKind: InputQueued})
	check(t, 7, got[7], want{Kind: KindHarnessText, Who: digest.Harness, Why: "commandMode task-notification", Text: "<task-notification>\n<summary>build lane finished</summary>\n</task-notification>"})
	check(t, 8, got[8], want{Kind: KindAgentText, Who: digest.Agent, Text: "The target is cache; it passes."})
	check(t, 9, got[9])
	check(t, 10, got[10])
	// The turn after the agent stopped: what Claude Code recorded just before it.
	check(t, 11, got[11],
		want{Kind: KindAgentText, Who: digest.Agent, Why: whyAgentInTurn, Text: "Here is a note offered by a side agent:\n\n> The cache test is flaky on main.\n> - Consider pinning the seed.", InputKind: InputTyped, Prior: "turn_duration"},
		want{Kind: KindOwnerText, Who: digest.Owner, Text: "pin it and rerun the suite", InputKind: InputTyped, Prior: "turn_duration"})
	check(t, 12, got[12],
		want{Kind: KindHarnessText, Who: digest.Harness, Text: "<command-message>goal</command-message>\n<command-name>/goal</command-name>", InputKind: InputSlash},
		want{Kind: KindOwnerText, Who: digest.Owner, Text: "ship the cache fix before friday", InputKind: InputSlash})
	check(t, 13, got[13], want{Kind: KindHarnessText, Who: digest.Harness, Why: "meta line", Text: "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"})
	// A command Claude Code ran itself: its arguments are input to it, not
	// words to the agent.
	check(t, 14, got[14], want{Kind: KindHarnessText, Who: digest.Harness, Why: "local command", Text: "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>", InputKind: InputSlash})
	check(t, 15, got[15], want{Kind: KindHarnessText, Who: digest.Harness, Text: "<bash-input>git status --short</bash-input>", InputKind: InputShell})
	check(t, 16, got[16], want{Kind: KindHarnessText, Who: digest.Harness, Text: "<bash-stdout> M Makefile</bash-stdout><bash-stderr></bash-stderr>", InputKind: InputShell})
	check(t, 17, got[17], want{Kind: KindAgentText, Who: digest.Agent, Why: "accepted suggestion", Text: "Run the cache tests again", InputKind: InputSuggestion})
	check(t, 18, got[18], want{Kind: KindToolCall, Who: digest.Agent, ToolID: "toolu_03", ToolName: askUser})
	check(t, 19, got[19], want{Kind: KindToolResult, Who: digest.Harness, ToolID: "toolu_03", ToolName: askUser, InputKind: InputAnswer})
	// A paste the desktop app framed is not their words.
	check(t, 20, got[20],
		want{Kind: KindAgentText, Who: digest.Agent, Why: whyAgentInTurn, Text: `<pasted_content id="1">panic: cache miss at key 7</pasted_content>`, InputKind: InputTyped},
		want{Kind: KindOwnerText, Who: digest.Owner, Text: "this fails here   fix it", InputKind: InputTyped})
	check(t, 21, got[21], want{Kind: KindHarnessText, Who: digest.Harness, Why: "api error", Text: "API Error: 529 overloaded", IsError: true})
	check(t, 22, got[22]) // the boundary is a record (Prior); its summary is the compaction
	check(t, 23, got[23], want{Kind: KindCompaction, Who: digest.Harness, Why: "compaction summary", Text: "This session is being continued from a previous conversation that ran out of context. Summary: the cache work."})
	check(t, 24, got[24], want{Kind: KindHarnessText, Who: digest.Harness, Why: "hook UserPromptSubmit", Text: "# tacit\n- RULE never purge the cache on main"})
	check(t, 25, got[25])
	check(t, 26, got[26], want{Kind: KindOwnerText, Who: digest.Owner, Text: "carry on with the cache work", InputKind: InputTyped, Prior: "compact_boundary"})

	// Every event carries its session, place and time; a reply's model
	// stays the model's, not the harness's own error message.
	for _, e := range evs {
		if e.Harness != "claude" || e.Session != claudeSession || e.Subagent != "" || e.Cwd != "/home/u/projects/shop" || e.Path != path || e.At.IsZero() {
			t.Fatalf("event fields: %+v", e)
		}
	}
	if e := got[26][0]; e.Model != "claude-opus-5-5" || !e.At.Equal(time.Date(2026, 10, 20, 10, 20, 0, 0, time.UTC)) {
		t.Errorf("model and time: %q %v", e.Model, e.At)
	}
	if e := got[0][1]; e.Model != "" {
		t.Errorf("a turn before any reply names no model: %q", e.Model)
	}
	if out := got[2][0].ToolOutput; out != "make: *** No rule to make target 'cache-check'." {
		t.Errorf("tool output: %q", out)
	}
	if out := got[5][0].ToolOutput; out != "cache:\n\tgo run ./cmd/cache" {
		t.Errorf("tool output from text blocks: %q", out)
	}
	if in := got[1][1].ToolInput; in != `{"command":"make cache-check"}` {
		t.Errorf("tool input: %q", in)
	}
}

// A subagent's transcript is an agent's: its brief is another agent's
// prompt, its lines carry the parent session and the subagent's id. A
// headless session's prompt is an agent's too.
func TestClaudeSubagentAndHeadlessSessions(t *testing.T) {
	home := t.TempDir()
	project := filepath.Join(home, ".claude", "projects", "-home-u-projects-shop")
	sub := func(m int, fields string) string {
		return fmt.Sprintf(`{%s,"timestamp":"2026-10-20T11:%02d:00.000Z","isSidechain":true,"agentId":"a7b8c9","userType":"external","entrypoint":"cli","cwd":"/home/u/projects/shop","sessionId":"%s","version":"2.1.302"}`, fields, m, claudeSession)
	}
	lines := []string{
		sub(0, `"parentUuid":null,"type":"user","uuid":"sa0","message":{"role":"user","content":"Find every place the cache key is built and report the files."}`),
		sub(1, `"type":"assistant","uuid":"sa1","message":{"model":"claude-sonnet-5-5","role":"assistant","content":[{"type":"tool_use","id":"toolu_s1","name":"Grep","input":{"pattern":"cacheKey"}}]}`),
		sub(2, `"type":"user","uuid":"sa2","sourceToolAssistantUUID":"sa1","message":{"role":"user","content":[{"tool_use_id":"toolu_s1","type":"tool_result","content":"cache/key.go:12"}]}`),
		sub(3, `"type":"assistant","uuid":"sa3","message":{"model":"claude-sonnet-5-5","role":"assistant","content":[{"type":"text","text":"cache/key.go builds it."}]}`),
	}
	path := write(t, filepath.Join(project, claudeSession, "subagents", "agent-a7b8c9.jsonl"), lines...)
	evs, _ := readAll(t, path, digest.Claude, 0)
	got := byLine(t, lines, evs)
	check(t, 0, got[0], want{Kind: KindAgentText, Who: digest.Agent, Why: "claude subagent", Text: "Find every place the cache key is built and report the files."})
	check(t, 1, got[1], want{Kind: KindToolCall, Who: digest.Agent, ToolID: "toolu_s1", ToolName: "Grep"})
	check(t, 2, got[2], want{Kind: KindToolResult, Who: digest.Harness, ToolID: "toolu_s1", ToolName: "Grep"})
	check(t, 3, got[3], want{Kind: KindAgentText, Who: digest.Agent, Text: "cache/key.go builds it."})
	for _, e := range evs {
		if e.Session != claudeSession || e.Subagent != "a7b8c9" {
			t.Fatalf("subagent event: session %q subagent %q", e.Session, e.Subagent)
		}
	}

	lane := write(t, filepath.Join(project, "lane.jsonl"),
		`{"type":"user","uuid":"l0","promptSource":"sdk","message":{"role":"user","content":"summarize the cache docs"},"timestamp":"2026-10-20T12:00:00.000Z","entrypoint":"sdk-cli","cwd":"/home/u/projects/shop","sessionId":"lane-1"}`)
	evs, _ = readAll(t, lane, digest.Claude, 0)
	check(t, 0, evs, want{Kind: KindAgentText, Who: digest.Agent, Why: "entrypoint sdk-cli", Text: "summarize the cache docs"})
}

// A paste the owner's prompt history records (Claude Code's CLI puts its
// text inline in the turn) is not their words, as the corpus holds: the
// owner_text is what they typed around it, the paste an agent's.
func TestClaudePasteFromThePromptHistory(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	paste := "panic: runtime error: index out of range [3] with length 3 in cache.go"
	write(t, filepath.Join(home, ".claude", "history.jsonl"),
		`{"display":"why does this fail [Pasted text #1 +1 lines]","pastedContents":{"1":{"id":1,"type":"text","content":"`+paste+`"}},"sessionId":"`+claudeSession+`","project":"/home/u/projects/shop"}`)
	lines := []string{cl(0, `"type":"user","uuid":"u0",`+typedMarks+`,"message":{"role":"user","content":"why does this fail\n`+paste+`"}`)}
	path := write(t, filepath.Join(home, ".claude", "projects", "-home-u-projects-shop", claudeSession+".jsonl"), lines...)
	evs, _ := readAll(t, path, digest.Claude, 0)
	check(t, 0, evs,
		want{Kind: KindOwnerText, Who: digest.Owner, Text: "why does this fail\n ", InputKind: InputTyped},
		want{Kind: KindAgentText, Who: digest.Agent, Why: whyLeftOut, Text: paste, InputKind: InputTyped})
}
