package index

import (
	"strings"
	"testing"

	"github.com/agent-sh/tacit/client/internal/fact"
)

func mk(path, name, scope, desc, superseded string) *fact.Fact {
	return &fact.Fact{Path: path, Meta: fact.Meta{Name: name, Scope: scope, Description: desc, SupersededBy: superseded}}
}

// A retired fact (outdated per git) leaves the index like a superseded one.
func TestGenerateSkipsRetired(t *testing.T) {
	gone := mk("projects/widget/gone.md", "gone", "projects/widget", "outdated", "")
	gone.Meta.Retired = "2026-10-09"
	got := Generate([]*fact.Fact{gone, mk("projects/widget/kept.md", "kept", "projects/widget", "current", "")})
	if strings.Contains(got, "gone") || !strings.Contains(got, "[kept]") {
		t.Fatalf("index:\n%s", got)
	}
}

func TestGenerate(t *testing.T) {
	facts := []*fact.Fact{
		mk("projects/widget/b.md", "b", "projects/widget", "second  line\nwrapped", ""),
		mk("projects/widget/a.md", "a", "projects/widget", "first", ""),
		mk("machines/host-a/old.md", "old", "machines/host-a", "superseded", "newer"),
		mk("machines/host-a/newer.md", "newer", "machines/host-a", "current", ""),
		mk("inbox/claude@host-a/x.md", "x", "user", "raw", ""),
	}
	got := Generate(facts)
	want := "# Memory index\n\nGenerated by `tacit index`. Do not edit.\n\n## machines/host-a\n\n- [newer](machines/host-a/newer.md) - current\n\n## projects/widget\n\n- [a](projects/widget/a.md) - first\n- [b](projects/widget/b.md) - second line wrapped\n"
	if got != want {
		t.Fatalf("\n got %q\nwant %q", got, want)
	}
	if strings.Contains(got, "inbox") || strings.Contains(got, "old") {
		t.Fatal("inbox or superseded fact indexed")
	}
	if Generate(facts) != got {
		t.Fatal("not deterministic")
	}
}
