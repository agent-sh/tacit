// Proposal is a split entry's proposal of a new area or topic.
type Proposal struct {
	Kind        string `json:"kind"` // area | topic
	Name        string `json:"name"`
	Area        string `json:"area,omitempty"` // a topic's area, when one owns it
	Description string `json:"description"`
}

// Folder is one live area or topic the split prompt lists.
type Folder struct {
	Scope, Kind, Description string
	Tools, Commands, Repos   []string
}

// FoldersSection is what the split prompt adds in a store of the folder
// records format: the live areas and topics an entry may take as its scope
// (at most maxListed), and how to propose one when none fits. Empty folders
// still get the proposal rule.
func FoldersSection(folders []Folder) string {
	var b strings.Builder
	b.WriteString("\nAREAS AND TOPICS:\nAn area is an ongoing system or practice of the owner's (the ticketing system, the on-call), a topic a bounded work stream (a migration, a launch). An entry about one may take its folder as its scope, exactly as listed; code refuses any other area or topic scope. When the notes are about an area or topic none of these fits, file the entry as you would anyway and add to it \"propose\": {\"kind\": \"area\"|\"topic\", \"name\": \"<slug>\", \"area\": \"<the area a topic belongs to, if one does>\", \"description\": \"<one line>\"}; a folder is made only once notes of two different sessions propose it. An org (kind org) is an organization on the forge: an entry takes its folder as its scope only when it holds across the org's repositories, naming two or more of the repos listed for it or the org itself; code checks that, and refuses an org scope for a fact about one repository.\n")
	if len(folders) == 0 {
		b.WriteString("(none yet)\n")
	}
	for i, f := range folders {
		if i == maxListed {
			fmt.Fprintf(&b, "(and %d more)\n", len(folders)-maxListed)
			break
		}
		fmt.Fprintf(&b, "- %s (%s): %s", f.Scope, f.Kind, ClipLine(f.Description, 160))
		if len(f.Tools) > 0 {
			b.WriteString("; tools: " + strings.Join(f.Tools, ", "))
		}
		if len(f.Commands) > 0 {
			b.WriteString("; commands: " + strings.Join(f.Commands, ", "))
		}
		if len(f.Repos) > 0 {
			b.WriteString("; repos: " + strings.Join(f.Repos, ", "))
		}
		b.WriteString("\n")
	}
	return b.String()
}

const maxListed = 40

// ClipLine is s on one line, at most max runes.
func ClipLine(s string, max int) string { return fact.ClipDescription(s, max) }

// Runner is the model call; tests substitute it.
type Runner func(ctx context.Context, model, prompt string) (string, float64, error)

// RunCLI and JudgeCLI select independent runners for curation and judging.
func RunCLI(ctx context.Context, model, prompt string) (string, float64, error) {
	return runRole(ctx, "curate", model, prompt)
}
func JudgeCLI(ctx context.Context, model, prompt string) (string, float64, error) {
	return runRole(ctx, "judge", model, prompt)
}
func runRole(ctx context.Context, role, model, prompt string) (string, float64, error) {
	sid := dream.NewSessionID()
	_ = dream.Exclude(sid)
	res, err := modelrun.RunWithFallback(ctx, role, model, prompt, sid)
	if res.SessionID != "" {
		_ = dream.Exclude(res.SessionID)
	}
	return res.Text, res.CostUSD, err
}
func ClaudeCLI(ctx context.Context, model, prompt string) (string, float64, error) {
	return RunCLI(ctx, model, prompt)
}

// Batches groups inbox notes so each prompt stays under batchChars.
func Batches(notes []*fact.Fact) [][]*fact.Fact {
	var out [][]*fact.Fact
	var cur []*fact.Fact
	size := 0
	for _, n := range notes {
		sz := len(n.Body) + len(n.Meta.Description) + 100
		if len(cur) > 0 && size+sz > batchChars {
			out = append(out, cur)
			cur, size = nil, 0
		}
		cur = append(cur, n)
		size += sz
	}
	if len(cur) > 0 {
		out = append(out, cur)
	}
	return out
}

// Render writes the notes section of the split prompt.
func Render(batch []*fact.Fact) string {
	var b strings.Builder
	for _, n := range batch {
		body := strings.TrimSpace(n.Body)
		if len(body) > 12_000 {
			body = body[:12_000]
		}
		fmt.Fprintf(&b, "### note name=%s scope=%s kind=%s\ndescription: %s\n%s\n\n", n.Meta.Name, n.Meta.Scope, n.Meta.Source.Kind, n.Meta.Description, body)
	}
	return b.String()
}

var arrayRx = regexp.MustCompile(`(?s)\[.*\]`)

// Parse extracts entries from a model answer.
func Parse(result string) []Entry {
	m := arrayRx.FindString(strings.TrimSpace(result))
	if m == "" {
		return nil
	}
	var raws []json.RawMessage
	if json.Unmarshal([]byte(m), &raws) != nil {
		return nil
	}
	var out []Entry
	for _, r := range raws {
		var x Entry
		if json.Unmarshal(r, &x) == nil && strings.TrimSpace(x.Description) != "" && x.Origin != "" {
			out = append(out, x)
		}
	}
	return out
}

var scopeRx = regexp.MustCompile(`^(user|system|projects/[a-z0-9-]+|machines/[a-z0-9-]+|areas/[a-z0-9][a-z0-9-]*(/topics/[a-z0-9][a-z0-9-]*)?|topics/[a-z0-9][a-z0-9-]*|orgs/[a-z0-9][a-z0-9-]*)$`)

// ToFact turns an entry into a curated fact; taken dedupes names.
func ToFact(e Entry, host string, taken map[string]bool) *fact.Fact {
	scope := e.Scope
	if !scopeRx.MatchString(scope) {
		scope = "user"
	}
	name := importer.Slug(e.Name, 80)
	if name == "fact" {
		name = importer.Slug(e.Description, 60)
	}
	if taken[name] {
		// The suffix is the description's hash, so a second entry of the
		// same name and description (one point filed in two folders) gets
		// the suffixed name again: that one must be free too.
		base := importer.Slug(name, 70) + "-" + shortHash(e.Description)
		name = base
		for i := 2; taken[name]; i++ {
			name = fmt.Sprintf("%s-%d", base, i)
		}
	}
	taken[name] = true
	typ := e.Type
	if !fact.Types[typ] || typ == "unclassified" {
		typ = "unclassified"
	}
	if e.Kind == KindStatement {
		// The point's type until code makes it a statement (ApplyStatement):
		// a model never gives the statement type itself.
		if d, ok := fact.TypeDocOf(typ); !ok || d.Owner || d.Generated || d.InboxOnly {
			typ = "design_decision"
		}
	}
	kind := e.Kind
	if !fact.SourceKinds[kind] || kind == "derived" {
		kind = "observed"
	}
	desc := fact.ClipDescription(e.Description, 200)
	body := strings.Join(strings.Fields(e.Body), " ")
	if body == "" {
		body = desc
	}
	return &fact.Fact{
		Path: scope + "/" + name + ".md",
		Meta: fact.Meta{
			Name: name, Description: desc, Type: typ, Scope: scope,
			AppliesTo: fact.AppliesTo{Paths: strs(e.AppliesTo["paths"]), Repos: strs(e.AppliesTo["repos"]), Hosts: strs(e.AppliesTo["hosts"]), Commands: strs(e.AppliesTo["commands"])},
			Source:    fact.Source{Harness: "curator", Host: host, Kind: kind},
			Created:   time.Now().Format("2006-01-02"),
			Origin:    e.Origin,
		},
		Body: body + "\n",
	}
}

func strs(xs []any) []string {
	var out []string
	for _, x := range xs {
		if s, ok := x.(string); ok && s != "" && len(out) < 8 {
			out = append(out, s)
		}
	}
	return out
}

func shortHash(s string) string {
	var h uint32 = 2166136261
	for i := 0; i < len(s); i++ {
		h ^= uint32(s[i])
		h *= 16777619
	}
	return fmt.Sprintf("%06x", h&0xffffff)
}

// Verdict of a conflict check.
type Verdict string

const (
	NoConflict  Verdict = "no"
	Contradicts Verdict = "contradicts"
	Supersedes  Verdict = "supersedes"
)

// ParseVerdict reads the one-word judge answer.
func ParseVerdict(s string) Verdict {
	s = strings.ToLower(strings.TrimSpace(s))
	switch {
	case strings.HasPrefix(s, "contradict"):
		return Contradicts
	case strings.HasPrefix(s, "supersede"):
		return Supersedes
	}
	return NoConflict
}

