func curatedAt(scope, name, desc, body string) *fact.Fact {
	return &fact.Fact{Path: scope + "/" + name + ".md", Meta: fact.Meta{Name: name, Description: desc, Type: "machine_fact", Scope: scope, Source: fact.Source{Kind: "observed", Harness: "curator"}}, Body: body}
}

func dreamNote(scope, name, body string) *fact.Fact {
	return &fact.Fact{Path: "inbox/dreamer@h/" + name + ".md", Meta: fact.Meta{Name: name, Description: body, Type: "machine_fact", Scope: scope, Source: fact.Source{Kind: "observed", Harness: "dreamer"}}, Body: body}
}

// The measurement's case: a paraphrase of a curated fact whose description
// shares too few terms for the description rule, every claim in the cover.
func TestContentRuleAbsorbsAParaphrase(t *testing.T) {
	kept := curatedAt("machines/box", "config-toml-generated-by-conf-sync-1f708f",
		"config.toml files are generated by conf-sync from ~/.config/conf/BASE.toml and local-extra.toml; edit those sources, never the generated config.toml.",
		"Edits made directly to a generated config.toml are overwritten on the next conf-sync.\n")
	a := NewAbsorber([]*fact.Fact{kept})
	f := curatedAt("machines/box", "config-toml-generated-by-conf-sync-cb6443",
		"config.toml is generated by conf-sync from /home/u/.config/conf/BASE.toml and local-extra.toml; edit those sources, not the generated config.toml.",
		"Edits made to a generated config.toml are overwritten on the next conf-sync.\n")
	note := dreamNote("machines/box", "n1", f.Meta.Description)
	if by := a.Restates(f, false); by != "" {
		t.Fatalf("the description rule took it (%s): the fixture tests nothing", by)
	}
	ab, ok := a.Absorbs(f, false, note)
	if !ok || ab.Rule != "content" || ab.By != kept.Meta.Name || ab.ByPath != kept.Path || ab.Coverage < ContentCover || ab.Note != "n1" {
		t.Fatalf("not absorbed by content: %+v %v", ab, ok)
	}
}

func TestContentRuleGuards(t *testing.T) {
	base := curatedAt("machines/box", "quokka-port", "The quokka scheduler on the build host listens on port 7781 behind the proxy.", "Its health check is `curl -s localhost:7781/health`.\n")
	paths := curatedAt("machines/box", "runner-logs", "Sandboxed jobs in a runner write stderr to /run/user/1000/rn/<runner-id>/jobs/<job-id>.stderr.log.", "Startup lock warnings there are not failures.\n")
	registered := curatedAt("machines/box", "fork-registered", "The fork acme/desktop-shell is registered with lintbot for reviews.", "Reviews of its PRs run through lintbot.\n")
	overview := curatedAt("projects/dispatch", "_overview", "Dispatch: the job runner of acme, its workers, its config files, the decisions that shaped it and its open questions.", "A relayed request is not owner approval for dispatch workers; workers follow the release checklist.\n")
	long := curatedAt("machines/box", "memory-import", "Imported memory of the box covering many tools.", strings.Repeat("The heron daemon restarts nightly and the quokka scheduler on the build host listens behind the proxy. ", 14))
	other := curatedAt("projects/elsewhere", "elsewhere-fact", "The walrus cache lives in /srv/walrus/cache and is pruned weekly by walrus-prune.", "Pruning runs at 03:00.\n")
	sessionRepo := curatedAt("projects/task-board", "tb-agent-env", "Run task-board CLI as orchestrator with `export TASK_BOARD_AGENT=orchestrator`, from ~/projects/acme/task-board.", "Orchestrator commands need TASK_BOARD_AGENT=orchestrator.\n")
	a := NewAbsorber([]*fact.Fact{base, paths, registered, overview, long, other, sessionRepo})
	cases := []struct {
		name  string
		f     *fact.Fact
		note  *fact.Fact
		wants bool
	}{
		{"same claim again", curatedAt("machines/box", "quokka-port-2", "The quokka scheduler on the build host listens on port 7781, behind the proxy.", "Health check: `curl -s localhost:7781/health`.\n"), nil, true},
		{"another port", curatedAt("machines/box", "quokka-port-3", "The quokka scheduler on the build host listens on port 7790 behind the proxy.", "\n"), nil, false},
		{"a new path past a placeholder", curatedAt("machines/box", "runner-logs-2", "Jobs in a runner write stderr to /run/user/1000/rn/<runner-id>/jobs/*.stderr.log.", "\n"), nil, false},
		{"a negation the cover lacks", curatedAt("machines/box", "fork-not-registered", "The fork acme/desktop-shell is not registered with lintbot for reviews.", "\n"), nil, false},
		{"a folder overview is no cover", curatedAt("projects/dispatch", "relayed", "A relayed request is not owner approval for dispatch workers.", "\n"), nil, false},
		{"a long import is no cover", curatedAt("machines/box", "heron", "The heron daemon restarts nightly.", "\n"), nil, false},
		{"another project's fact is not visible", curatedAt("projects/mine", "walrus", "The walrus cache lives in /srv/walrus/cache and is pruned weekly by walrus-prune.", "\n"), nil, false},
		{"the session's repository is visible", curatedAt("machines/box", "tb-env-2", "Run task-board orchestrator commands with `export TASK_BOARD_AGENT=orchestrator` from ~/projects/acme/task-board.", "\n"), dreamNote("projects/task-board", "tb-note", "x"), true},
		{"the session's repository from another note", curatedAt("machines/box", "tb-env-3", "Run task-board orchestrator commands with `export TASK_BOARD_AGENT=orchestrator` from ~/projects/acme/task-board.", "\n"), dreamNote("machines/box", "tb-note-2", "x"), false},
	}
	for _, c := range cases {
		if _, ok := a.Absorbs(c.f, false, c.note); ok != c.wants {
			t.Errorf("%s: absorbed %v, want %v", c.name, ok, c.wants)
		}
	}
}

// The owner's words are never absorbed by content: a note in their words, a
// statement, a quoted span of six words, a reviewer's trim.
func TestContentRuleKeepsTheOwnersWords(t *testing.T) {
	kept := curatedAt("user", "release-checklist", "The release checklist for agents is in ~/.config/acme/checklists/release.md.", "Read ~/.config/acme/checklists/release.md before tagging or publishing a release.\n")
	a := NewAbsorber([]*fact.Fact{kept})
	f := func() *fact.Fact {
		return curatedAt("user", "release-checklist-2", "Agents read ~/.config/acme/checklists/release.md before tagging or publishing a release.", "\n")
	}
	if by := a.Restates(f(), false); by != "" {
		t.Fatal("the description rule took it: the fixture tests nothing")
	}
	if ab, ok := a.Absorbs(f(), false, dreamNote("user", "plain", "x")); !ok || ab.Rule != "content" {
		t.Fatal("the plain copy was not absorbed: the fixture tests nothing")
	}
	user := dreamNote("user", "said", "x")
	user.Meta.Source.Kind = "user"
	quoted := dreamNote("user", "quoted", `The owner said "always read the release checklist before any release" today.`)
	trimmed := dreamNote("user", "agent-note-trimmed", "x")
	words := f()
	words.Meta.Source.OwnerWords = "read the checklist"
	for name, c := range map[string]struct{ f, note *fact.Fact }{
		"note in their words": {f(), user},
		"quoted span":         {f(), quoted},
		"reviewer trim":       {f(), trimmed},
		"fact with words":     {words, nil},
	} {
		if _, ok := a.Absorbs(c.f, false, c.note); ok {
			t.Errorf("%s: absorbed", name)
		}
	}
	if _, ok := a.Absorbs(f(), true, nil); ok {
		t.Error("a ruling was absorbed by content")
	}
}

// Claims may be covered by different facts; a retired fact covers nothing.
func TestContentRuleClaimsAcrossFactsAndDrop(t *testing.T) {
	one := curatedAt("machines/box", "borg-repo", "Local borg repo is /home/u/archive/borg for payload backups.", "\n")
	two := curatedAt("machines/box", "borg-passphrase", "The borg passphrase file lives under ~/.config/borg-pass for the local repo.", "\n")
	a := NewAbsorber([]*fact.Fact{one, two})
	f := curatedAt("machines/box", "borg-both", "Local borg repo is ~/archive/borg for payload backups.", "The borg passphrase file lives under ~/.config/borg-pass for the local repo.\n")
	if _, ok := a.Absorbs(f, false, nil); !ok {
		t.Fatal("two claims covered by two facts were not absorbed")
	}
	a.Drop(two.Path)
	if _, ok := a.Absorbs(f, false, nil); ok {
		t.Fatal("a retired fact still covered a claim")
	}
}

func TestSentencesKeepCodeSpansWhole(t *testing.T) {
	got := sentences("Heartbeat: `timeout 40 ssh host-a 'cd ~/x; ls jobs'`. Then e.g. read it; done.\nNext")
	want := []string{"Heartbeat: `timeout 40 ssh host-a 'cd ~/x; ls jobs'`", "Then e.g. read it", "done", "Next"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("%q", got)
	}
}
