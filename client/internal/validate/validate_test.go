func TestAttributionOnlyOnARuling(t *testing.T) {
	for _, d := range []string{"Owner ruling: never push to main", "The owner's rule is to rebase", "Per owner rule, tags are signed", "owner ruled 2026-10-01 that X"} {
		if Attribution(d, "", false) == nil {
			t.Errorf("observation %q passed", d)
		}
		if Attribution(d, "", true) != nil {
			t.Errorf("ruling %q refused", d)
		}
	}
	if Attribution("Tags are signed", "Why: the owner ruled it in [[tag-rule]].", false) == nil {
		t.Error("attribution in the body passed")
	}
	for _, d := range []string{"The repo owner field is empty", "Owners file lists two rulers", "The owner prefers tables"} {
		if Attribution(d, "", false) != nil {
			t.Errorf("%q refused", d)
		}
	}
}

func TestMetaJoinsEveryCheck(t *testing.T) {
	e := env(t)
	m := fact.Meta{Name: "x", Description: "Owner ruling: use port 7781", Type: "hot_spot", Scope: "projects/kv-013-g1", AppliesTo: fact.AppliesTo{Repos: []string{"client"}, Paths: []string{"/abs/path"}}, Source: fact.Source{Kind: "observed"}}
	ps := e.Meta(m, "body", false, false)
	fields := map[string]bool{}
	for _, p := range ps {
		fields[p.Field] = true
		if strings.Contains(p.String(), "kv-013-g1") || strings.Contains(p.String(), "client") {
			t.Errorf("a logged problem holds the writer's value: %s", p.String())
		}
	}
	for _, f := range []string{"scope", "type", "applies_to.repos", "applies_to.paths", "description"} {
		if !fields[f] {
			t.Errorf("no problem for %s: %v", f, ps)
		}
	}
	// An inbox note may claim kind user (the curator decides) with the wording.
	m = fact.Meta{Description: "Owner ruling: sign tags", Type: "unclassified", Scope: "user", Source: fact.Source{Kind: "user"}}
	if ps := e.Meta(m, "", true, false); len(ps) != 0 {
		t.Errorf("an inbox claim refused: %v", ps)
	}
	if err := Error(e.Meta(fact.Meta{Type: "past_mistake", Scope: "user", Source: fact.Source{Kind: "observed"}}, "", true, false)); err != nil {
		t.Errorf("a clean note refused: %v", err)
	}
}
