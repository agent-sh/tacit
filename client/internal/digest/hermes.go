package digest

import (
	"encoding/json"
	"regexp"
	"strings"
)

// HermesMessage is one row of a Hermes session (the messages table of
// ~/.hermes/state.db): role user, assistant, tool or session_meta; the tool
// calls an assistant row made (a JSON list of {"function": {"name",
// "arguments"}}); the tool a tool row answers; display_kind, which marks the
// gateway's own notices; and _compressed_summary, a compaction summary.
type HermesMessage struct {
	Role, Content, ToolCalls, ToolName, DisplayKind string
	Summary                                         bool
}

// hermesNotices are display kinds of user rows the gateway wrote: a
// notification, a finished delegation or background process, a model switch.
// "steer" is a message of the owner's delivered mid-turn, framed (below).
var hermesNotices = map[string]bool{"internal_notification": true, "async_delegation_complete": true, "process_complete": true, "model_switch": true}

var (
	// hermesWhole opens a user row that is the harness's from start to end:
	// the handoff summary of a compaction, a request restated after one, a
	// finished delegation or process, a cron job's prompt or delivery, the
	// task list kept across compression, a notice or a pruned skill.
	hermesWhole = regexp.MustCompile(`^\[(CONTEXT COMPACTION|STILL IN PROGRESS|ASYNC DELEGATION|IMPORTANT:|INTERNAL NOTIFICATION|Cron delivery:|Your active task list|SKILL PRUNED)`)
	// hermesFixed are user rows with no bracket the harness writes: the
	// iteration limit, a lost turn lease, a kanban task's result and the file
	// edit verifier's warning.
	hermesFixed = []string{"You've reached the maximum number of tool-calling iterations", "Session turn lease could not be refreshed", "✔ [", "✖ [", "⚠️ File-mutation verifier"}
	// hermesGenerated anywhere in a row means the gateway wrote it.
	hermesGenerated = "[INTERNAL NOTIFICATION — generated by the Hermes gateway"
	// hermesVoice is a voice message: what they said is the transcript in it.
	hermesVoice = regexp.MustCompile(`(?s)\[The user sent a voice message\W*Here's what they said: "(.*?)"\](\n|$)`)
	// hermesQuoted opens a reply: the message it quotes is an agent's, not
	// theirs, and runs to the last `"]` (the quote may hold `"]` itself).
	hermesQuoted = `[Replying to: "`
	// hermesOutOfBand frames a message of theirs delivered during a turn: a
	// header, the gateway's origin data and a line of instructions come before
	// their words.
	hermesOutOfBand = regexp.MustCompile(`(?s)\[OUT-OF-BAND USER MESSAGE[^\n]*\](.*?)\[/OUT-OF-BAND USER MESSAGE\]`)
	hermesOrigin    = regexp.MustCompile(`(?s)^\s*Gateway message origin \(JSON data.*?Do not guess a reply destination when these fields are insufficient\.`)
	// hermesAttached opens the context Hermes appends for a reference the
	// owner wrote (@file:, @url:): the file or page, to the end of the row.
	hermesAttached = regexp.MustCompile(`(?m)^--- Attached Context ---\s*$`)
	// hermesPasteRef is the reference the desktop composer writes for a
	// paste: the pasted text is saved under .hermes/composer-pastes/ and
	// attached, so the reference is no word of theirs either.
	hermesPasteRef = regexp.MustCompile(`@file:\S*composer-pastes/\S*`)
	// hermesNote is a one-block note at the start of a line: an attachment
	// saved for the agent, a model switch, a system note, the workspace.
	hermesNote = regexp.MustCompile(`(?ms)^\[(The user sent an? |Note: |System note: |System: |Workspace::)[^\n]*?\](\n|$)`)
)

// HermesOwnerText is what the owner wrote in a Hermes user row, and whether
// none of it is theirs. Hermes frames their words: a reply quotes the message
// it answers, a voice message is a transcript in a note, a message sent while
// the agent works comes with the gateway's origin data, an attachment or a
// model switch adds a note, and a reference (@file:, @url:) comes with the
// file or page attached after it (a paste in the desktop app is such a file,
// under composer-pastes/). Those frames, the attached context and a paste's
// reference are cut and the rest is theirs. A
// row the gateway wrote (a display kind of its notices, a compaction summary,
// a row that opens with one of its headers or says it was generated by it)
// holds nothing of theirs, and so does a row that still opens with a bracket
// once the frames are cut (an unknown notice; fail closed).
func HermesOwnerText(content, displayKind string, summary bool) (string, bool) {
	t := strings.TrimSpace(content)
	if summary || hermesNotices[displayKind] || strings.Contains(t, hermesGenerated) || hermesWhole.MatchString(t) {
		return "", true
	}
	for _, p := range hermesFixed {
		if strings.HasPrefix(t, p) {
			return "", true
		}
	}
	if m := hermesAttached.FindStringIndex(t); m != nil {
		t = t[:m[0]]
	}
	t = hermesPasteRef.ReplaceAllString(t, "")
	t = hermesOutOfBand.ReplaceAllStringFunc(t, func(m string) string {
		inner := hermesOutOfBand.FindStringSubmatch(m)[1]
		return hermesOrigin.ReplaceAllString(inner, "") + "\n"
	})
	t = hermesOrigin.ReplaceAllString(t, "")
	// The frames before their words, in any order: notes, and the message a
	// reply quotes, cut first so nothing inside the quote is read as theirs.
	for {
		t = strings.TrimSpace(t)
		if m := hermesVoice.FindStringSubmatchIndex(t); m != nil && m[0] == 0 {
			break // a voice message is a note too, but holds their words
		}
		if m := hermesNote.FindStringIndex(t); m != nil && m[0] == 0 {
			t = t[m[1]:]
			continue
		}
		if strings.HasPrefix(t, hermesQuoted) {
			i := strings.LastIndex(t, `"]`)
			if i < len(hermesQuoted) {
				return "", true
			}
			t = t[i+2:]
			continue
		}
		break
	}
	t = hermesVoice.ReplaceAllString(t, "$1\n")
	t = hermesNote.ReplaceAllString(t, "")
	t = strings.TrimSpace(t)
	if t == "" || strings.HasPrefix(t, "[") {
		return "", true
	}
	return t, false
}

// HermesLines digests the rows of an owner session in order: U: for what the
// owner wrote in a user row (HermesOwnerText), H: for a user row with nothing
// of theirs, A: for assistant text, T: for each tool call, E: for a tool row
// that reports a failure.
func HermesLines(ms []HermesMessage) []string {
	var out []string
	for _, m := range ms {
		switch m.Role {
		case "user":
			if strings.TrimSpace(m.Content) == "" {
				continue
			}
			if txt, injected := HermesOwnerText(m.Content, m.DisplayKind, m.Summary); injected {
				out = append(out, "H: "+clip(m.Content, hMax))
			} else {
				out = append(out, "U: "+clip(txt, uMax))
			}
		case "assistant":
			if strings.TrimSpace(m.Content) != "" {
				out = append(out, "A: "+clip(m.Content, aMax))
			}
			var calls []struct {
				Function struct {
					Name      string `json:"name"`
					Arguments string `json:"arguments"`
				} `json:"function"`
			}
			if json.Unmarshal([]byte(m.ToolCalls), &calls) == nil {
				for _, c := range calls {
					var args any = map[string]any{}
					var am map[string]any
					if json.Unmarshal([]byte(c.Function.Arguments), &am) == nil {
						args = am
					}
					out = append(out, toolLine(c.Function.Name, args))
				}
			}
		case "tool":
			if e, ok := hermesToolError(m.Content); ok {
				out = append(out, "E: "+clip(strings.TrimSpace(m.ToolName+": "+e), eMax))
			}
		}
	}
	return out
}

// hermesToolError is the failure a tool row reports: a JSON result with an
// error, a nonzero exit_code, success or ok false; or plain text that opens
// with "Error". Other plain text is a file, a page or a listing, where the
// word error says nothing.
func hermesToolError(content string) (string, bool) {
	t := strings.TrimSpace(content)
	var o map[string]any
	if strings.HasPrefix(t, "{") && json.Unmarshal([]byte(t), &o) == nil {
		msg := ""
		switch e := o["error"].(type) {
		case string:
			msg = e
		case bool:
			if e {
				msg = "error"
			}
		case nil:
		default:
			b, _ := json.Marshal(e)
			msg = string(b)
		}
		code, _ := o["exit_code"].(float64)
		if msg == "" && code == 0 && o["success"] != false && o["ok"] != false {
			return "", false
		}
		if strings.TrimSpace(msg) == "" || msg == "error" {
			for _, k := range []string{"stderr", "output", "message"} {
				if s, _ := o[k].(string); strings.TrimSpace(s) != "" {
					msg = s
					break
				}
			}
		}
		return msg, true
	}
	if errLead.MatchString(t) {
		return t, true
	}
	return "", false
}

var errLead = regexp.MustCompile(`^(?i)error\b`)
